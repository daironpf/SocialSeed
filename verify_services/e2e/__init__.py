# SocialSeed E2E Testing Framework
# =================================
#
# This package provides end-to-end testing capabilities for SocialSeed services.
#
# Quick Start:
#   1. Configure api.conf with your service URLs
#   2. Run tests: python run_complete_verification.py
#
# Structure:
#   e2e/core/        - Generic testing engine (service-agnostic)
#   e2e/services/    - Service-specific implementations
#   api.conf         - Central configuration file
